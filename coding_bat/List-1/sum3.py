# Given an array of ints length 3, return the sum of all the elements.

def sum3(nums):  # [1,2,3,4,5,6]
    total = 0  #
    for num in nums:  # num = 1
        total = total + num  # 0 + 1

    return total


print(sum3([1, 2, 3]))  # 6

print(sum3([1, 2, 3, 4, 5, 6]))  # 21


